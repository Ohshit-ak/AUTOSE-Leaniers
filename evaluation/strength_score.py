def _norm(t: str) -> str:
    return " ".join((t or "").split())


def _list_elems(v: str) -> Optional[List[str]]:
    v = v.strip()
    if not (v.startswith("[") and v.endswith("]")):
        return None
    return _split_commas(v[1:-1])


def _split_commas(s: str) -> List[str]:
    parts, depth, cur, in_str, esc = [], 0, "", False, False
    for c in s:
        if in_str:
            cur += c
            if esc:
                esc = False
            elif c == "\\":
                esc = True
            elif c == '"':
                in_str = False
            continue
        if c == '"':
            in_str = True
        elif c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        if c == "," and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += c
    parts.append(cur)
    return [p.strip() for p in parts if p.strip()]


def perturb(value: str, typ: str, types: Dict[str, Dict[str, str]], depth: int = 0) -> List[str]:
    """Changed versions of one field value of type `typ`."""
    t, v = _norm(typ), value.strip()
    if t == "Bool":
        return ["false" if v == "true" else "true"]
    if t in ("Nat", "Int"):
        try:
            n = int(v.strip("()"))
        except ValueError:
            return ["0", "1"]
        out = [str(n + 1)] + ([str(n - 1)] if n > 0 or t == "Int" else []) + (["0"] if n not in (0, 1) else [])
        return [o if not o.startswith("-") else f"({o})" for o in out]
    if t == "String":
        return ['""', v[:-1] + '#"' if v.endswith('"') and v != '""' else '"#"']
    if t.startswith("List"):
        elems = _list_elems(v)
        if elems is None:
            return ["[]"]
        if elems:
            return ["[]", "[" + ", ".join(elems + elems) + "]", "[" + ", ".join(elems[1:]) + "]"]
        inner = _norm(t[len("List"):]).strip("() ")
        e = {"Nat": "7", "Int": "7", "String": '"#"', "Bool": "true"}.get(inner)
        if e is None and inner in types and depth == 0:
            e = _default_record(inner, types)
        return [f"[{e}]"] if e else []
    if t.startswith("Option"):
        return ["none"] if v != "none" else []
    if t in types and depth == 0 and v.startswith("{"):
        sub, out = literal_fields(v), []
        for f, sv in sub.items():
            for m in perturb(sv, types[t].get(f, ""), types, depth + 1):
                if m.strip() != sv.strip():
                    out.append(_literal({**sub, f: m}))
        return out
    return []


def _default_record(name: str, types: Dict[str, Dict[str, str]]) -> Optional[str]:
    vals = {}
    for f, t in types.get(name, {}).items():
        t = _norm(t)
        d = {"Nat": "0", "Int": "0", "Bool": "false", "String": '""'}.get(t)
        if d is None:
            d = "[]" if t.startswith("List") else "none" if t.startswith("Option") else None
        if d is None:
            return None
        vals[f] = d
    return _literal(vals) if vals else None


def copy_mutants(inp: Dict[str, str], out: Dict[str, str], types: Dict[str, Dict[str, str]]) -> List[str]:
    """Outputs of the copy-and-constant implementations, on the example input. A field with no
    candidate keeps its example value."""
    tin, tout = types.get("Input", {}), types.get("Output", {})
    options = []
    for f, t in tout.items():
        cands = []
        for c in C._candidates(t, tin, f):
            if c.startswith("x."):
                g = c[2:]
                if g in inp:
                    cands.append(inp[g])
            else:
                cands.append(c)
        options.append(list(dict.fromkeys(cands)) or [out.get(f, "")])
    if not all(o and o[0] for o in options):
        return []
    return [_literal(dict(zip(tout, combo))) for combo in itertools.islice(itertools.product(*options),
                                                                         MAX_COPY_MUTANTS)]


EXTRA_INPUTS = 2          # inputs besides the example's on which copy implementations are run
MAX_INPUT_CANDIDATES = 8


def _input_variants(inp: Dict[str, str], types: Dict[str, Dict[str, str]]) -> List[str]:
    """Single-field changes of the example input (candidates; `pre` is checked by Lean)."""
    out, seen = [], {_norm(_literal(inp))}
    for f, v in inp.items():
        for p in perturb(v, types["Input"].get(f, ""), types):
            lit = _literal({**inp, f: p})
            if _norm(lit) not in seen:
                seen.add(_norm(lit))
                out.append(lit)
    return out[:MAX_INPUT_CANDIDATES]


def mutants(code: str, extra_inputs: Optional[List[str]] = None):
    """(example input literal, [(kind, input literal, output literal)]) or None without a usable
    example. Copy mutants run on the example input and on `extra_inputs` (which must satisfy
    `pre`); perturbations change one field of the example output."""
    w = example_witness(code)
    types = field_types(code)
    if not w or not types.get("Output") or not types.get("Input"):
        return None
    inp_lit, out_lit = w
    inp, out = literal_fields(inp_lit), literal_fields(out_lit)
    if set(out) != set(types["Output"]) or set(inp) != set(types["Input"]):
        return None
    seen, copies, pert = {(_norm(inp_lit), _norm(_literal(out)))}, [], []
    for il in [inp_lit] + list(extra_inputs or []):
        for m in copy_mutants(literal_fields(il), out, types):
            if (_norm(il), _norm(m)) not in seen:
                seen.add((_norm(il), _norm(m)))
                copies.append(("copy", il, m))
    for f, v in out.items():
        t = types["Output"].get(f, "")
        for p in list(dict.fromkeys(perturb(v, t, types) + _l05_mutants(v, t))):
            m = _literal({**out, f: p})
            if (_norm(inp_lit), _norm(m)) not in seen:
                seen.add((_norm(inp_lit), _norm(m)))
                pert.append(("perturb", inp_lit, m))
    pert = pert[:MAX_MUTANTS]
    return inp_lit, copies[:max(0, MAX_MUTANTS - len(pert))] + pert


def _l05_mutants(v: str, t: str) -> List[str]:
    from validate import _mutants   # the values L0.5's vacuity check uses
    try:
        return _mutants(v, t)
    except Exception:   # noqa: BLE001
        return []


