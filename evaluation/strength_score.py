def _local_grounded(spec_code: str, entry: dict) -> Tuple[bool, List[str]]:
    """Every number ≥ 2 and every non-empty string literal in `Spec.pre`/`Spec.post` must occur
    in the requirement text (numbers also as words). Returns (grounded, ungrounded constants)."""
    s = C.spec_contract(code_defs_only(spec_code))
    if s is None:
        return True, []
    body = s.pre + "\n" + s.post
    text = " ".join(str(entry.get(k) or "") for k in ("text", "description", "name", "goal", "requirement_text"))
    text += " " + " ".join(entry.get("postconditions") or []) + " " + " ".join(entry.get("preconditions") or [])
    low = text.lower()
    nums_in_text = {int(n.replace(",", "")) for n in re.findall(r"\d[\d,]*", text)}
    bad = []
    for n in sorted({int(n) for n in re.findall(r"(?<![\w.\"])(\d+)(?![\w.])", C._mask(body))}):
        if n < 2 or n in nums_in_text:
            continue
        if NUMBER_WORDS.get(n) and re.search(rf"\b{NUMBER_WORDS[n]}\b", low):
            continue
        bad.append(str(n))
    for lit in sorted(set(re.findall(r'"((?:[^"\\]|\\.)+)"', body))):
        if lit.lower() not in low:
            bad.append(f'"{lit}"')
    return not bad, bad


try:   # P8 (another script) may provide a better grounding check
    from p8_grounding import grounded as _grounded  # type: ignore
    GROUNDING = "p8_grounding.grounded"
except Exception:   # noqa: BLE001
    _grounded = _local_grounded
    GROUNDING = "local (numbers ≥ 2 and string literals of pre/post must occur in the requirement text)"


def grounded(spec_code: str, entry: dict) -> Tuple[bool, List[str]]:
    try:
        ok, bad = _grounded(spec_code, entry)
        return bool(ok), list(bad or [])
    except Exception:   # noqa: BLE001
        return _local_grounded(spec_code, entry)


