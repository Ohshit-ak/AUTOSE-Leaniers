def score_spec(r: dict, entry: dict) -> dict:
    """The P11 payoff for one stored specs.json result."""
    code = r.get("lean_predicate") or ""
    strength = (r.get("l05") or {}).get("strength") or {}
    out = {"id": r["id"], "kind": r.get("kind"), "class": strength.get("class") or "-",
           "l05": (r.get("l05") or {}).get("status"), "gate": None, "killed": 0, "mutants": 0,
           "killed_copy": 0, "copy": 0, "score": 0.0, "ungrounded": []}
    if not r.get("compiles") or not code.strip():
        out["gate"] = "unsatisfiable (does not compile)"
        return out
    if strength.get("output_free") or strength.get("class") == "unrealizable":
        out["gate"] = "unsatisfiable (output-free post conjunct)"
        return out
    ok, bad = grounded(code, entry)
    out["ungrounded"] = bad
    defs = code_defs_only(code)
    got = mutants(code)
    if got is None:
        out["gate"] = "untestable (no example in `Spec.post {…} {…}` form)"
        return out
    inp, _ = got
    # Lean run 1: which input variants satisfy `pre` (copy implementations also run on them)
    types = field_types(code)
    variants = _input_variants(literal_fields(inp), types)
    extra = []
    if variants:
        pre_ok = example_errors(defs, [f"example : Spec.pre {v} := by\n  unfold Spec; decide" for v in variants])
        extra = [v for v, e in zip(variants, pre_ok) if not e][:EXTRA_INPUTS]
    _, ms = mutants(code, extra)
    if not ms:
        out["gate"] = "untestable (no field types to vary)"
        return out
    # Lean run 2: every mutant
    checks = [f"example : ¬ Spec.post {i} {m} := by\n  unfold Spec; decide" for _, i, m in ms]
    errs = example_errors(defs, checks)
    if errs and all(e and str(e[0]).startswith("error in the spec itself") for e in errs):
        out["gate"] = "untestable (spec does not compile without its example)"
        return out
    killed = [not e for e in errs]
    out["mutants"], out["killed"] = len(ms), sum(killed)
    out["copy"] = sum(k == "copy" for k, _, _ in ms)
    out["killed_copy"] = sum(kl for (k, _, _), kl in zip(ms, killed) if k == "copy")
    out["inputs"] = 1 + len(extra)
    rate = out["killed"] / len(ms)
    out["rate"] = round(rate, 3)
    if not any(kl for (_, i, _), kl in zip(ms, killed) if i == inp):
        out["gate"] = "vacuous (rejects no changed output)"
    elif not ok:
        out["gate"] = "ungrounded"
    else:
        out["score"] = round(rate, 3)
    return out


def _entries(specs: dict) -> dict:
    try:
        from validate import entries_for
        return entries_for(specs)
    except Exception:   # noqa: BLE001
        return {}


def score_run(run: Path, workers: int = 8) -> dict:
    specs = json.loads((run / "specs.json").read_text(encoding="utf-8"))
    entries = _entries(specs)

    def one(r):
        e = dict(entries.get(r["id"]) or {})
        e.setdefault("requirement_text", r.get("requirement_text"))
        try:
            return score_spec(r, e)
        except Exception as ex:   # noqa: BLE001  one spec must not stop the run
            return {"id": r["id"], "kind": r.get("kind"), "class": "-", "l05": None, "gate": f"error: {ex}",
                    "killed": 0, "mutants": 0, "killed_copy": 0, "copy": 0, "score": 0.0, "ungrounded": []}
    with ThreadPoolExecutor(max_workers=workers) as ex:
        rows = list(ex.map(one, specs["results"]))
    return {"run": str(run.relative_to(ROOT)) if run.is_relative_to(ROOT) else str(run),
            "doc": run.parent.parent.name, "rows": rows}


def _pearson(xs: List[float], ys: List[float]) -> Optional[float]:
    if len(xs) < 3 or len(set(xs)) < 2 or len(set(ys)) < 2:
        return None
    mx, my = statistics.mean(xs), statistics.mean(ys)
    sxy = sum((a - mx) * (b - my) for a, b in zip(xs, ys))
    sx = sum((a - mx) ** 2 for a in xs) ** 0.5
    sy = sum((b - my) ** 2 for b in ys) ** 0.5
    return sxy / (sx * sy)


def _f(x, nd=2):
    return "–" if x is None else f"{x:.{nd}f}"


def report(results: List[dict]) -> str:
    all_rows = [row for r in results for row in r["rows"]]
    lines = ["# P11 strength scores (stored L0 specs)", "",
             "Generated by `python evaluation/strength_score.py` (no model; one Lean run per spec). "
             "Mechanism: `docs/design/p11_mechanism.md`.", "",
             f"Grounding check used: {GROUNDING}.", "",
             "payoff = 0 if unsatisfiable / vacuous / ungrounded, else the mutant-kill rate on the example input. "
             "*mean (all)* averages over every L0 entry (non-compiling = 0); *mean (scored)* over specs that "
             "passed every gate; *kill rate* is over every tested spec, gates ignored.", "",
             "## Per SRS", "",
             "| SRS | entries | compile | unsat | vacuous | ungrounded | untestable | scored | mean (all) | "
             "mean (scored) | kill rate (tested) |",
             "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in results:
        rows = r["rows"]
        g = Counter((x["gate"] or "scored").split(" ")[0] for x in rows)
        scored = [x["score"] for x in rows if not x["gate"]]
        tested = [x["rate"] for x in rows if "rate" in x]
        lines.append(f"| {r['doc']} | {len(rows)} | {sum(x['gate'] != 'unsatisfiable (does not compile)' for x in rows)} "
                     f"| {g['unsatisfiable']} | {g['vacuous']} | {g['ungrounded']} | {g['untestable'] + g['error:']} "
                     f"| {len(scored)} | {_f(statistics.mean([x['score'] for x in rows]) if rows else None)} "
                     f"| {_f(statistics.mean(scored) if scored else None)} "
                     f"| {_f(statistics.mean(tested) if tested else None)} |")
    g = Counter((x["gate"] or "scored").split(" ")[0] for x in all_rows)
    scored = [x["score"] for x in all_rows if not x["gate"]]
    tested = [x["rate"] for x in all_rows if "rate" in x]
    lines.append(f"| **all** | {len(all_rows)} | {sum(x['gate'] != 'unsatisfiable (does not compile)' for x in all_rows)} "
                 f"| {g['unsatisfiable']} | {g['vacuous']} | {g['ungrounded']} | {g['untestable'] + g['error:']} "
                 f"| {len(scored)} | {_f(statistics.mean([x['score'] for x in all_rows]))} "
                 f"| {_f(statistics.mean(scored) if scored else None)} | {_f(statistics.mean(tested) if tested else None)} |")

    lines += ["", "## By L0.5 strength class (`l05.strength.class`)", "",
              "| class | specs | tested | mean kill rate (tested) | copy mutants killed | mean payoff |",
              "|---|---|---|---|---|---|"]
    by = defaultdict(list)
    for x in all_rows:
        by[x["class"]].append(x)
    for cls in ("strong", "weak", "copy-ok", "unrealizable", "-"):
        xs = by.get(cls)
        if not xs:
            continue
        t = [x["rate"] for x in xs if "rate" in x]
        kc, nc = sum(x["killed_copy"] for x in xs), sum(x["copy"] for x in xs)
        lines.append(f"| {cls} | {len(xs)} | {len(t)} | {_f(statistics.mean(t) if t else None)} | "
                     f"{kc}/{nc} ({_f(100 * kc / nc if nc else None, 0)} %) | "
                     f"{_f(statistics.mean(x['score'] for x in xs))} |")
    sw = [x for x in all_rows if x["class"] in ("strong", "weak") and "rate" in x]
    r_rate = _pearson([float(x["class"] == "strong") for x in sw], [x["rate"] for x in sw])
    r_pay = _pearson([float(x["class"] == "strong") for x in sw], [x["score"] for x in sw])
    lines += ["", f"Point-biserial correlation, strong (1) vs weak (0), over {len(sw)} tested specs: "
              f"kill rate r = {_f(r_rate)}, payoff r = {_f(r_pay)}.", "",
              "By construction a weak spec accepts at least one copy/constant implementation for *every* input, "
              "so on the example input at least one copy mutant usually survives; the perturbation mutants are "
              "what separates specs within a class.", "",
              "## Gates (reasons a spec scores 0)", "", "| reason | specs |", "|---|---|"]
    for k, n in Counter(x["gate"] for x in all_rows if x["gate"]).most_common():
        lines.append(f"| {k} | {n} |")
    ung = Counter(c for x in all_rows if x["gate"] == "ungrounded" for c in x["ungrounded"])
    if ung:
        lines += ["", "Most frequent ungrounded constants: "
                  + ", ".join(f"`{c}` ({n})" for c, n in ung.most_common(15)) + "."]

    lines += ["", "## Per spec", ""]
    for r in results:
        lines += [f"### {r['doc']} (`{r['run']}`)", "",
                  "| id | class | L0.5 | killed / mutants (copy) | payoff | gate |", "|---|---|---|---|---|---|"]
        for x in r["rows"]:
            gate = x["gate"] or ""
            if x["gate"] == "ungrounded":
                gate += ": " + ", ".join(f"`{c}`" for c in x["ungrounded"][:4])
            lines.append(f"| {x['id']} | {x['class']} | {x['l05'] or '–'} | "
                         f"{x['killed']}/{x['mutants']} ({x['killed_copy']}/{x['copy']}) | {x['score']:.2f} | {gate} |")
        lines.append("")
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("runs", nargs="*", help="L0 run folders with specs.json")
    ap.add_argument("--all", action="store_true", help="every runs/*/qwen-v11/rep1")
    ap.add_argument("-o", "--out", help="markdown report (also writes <out>.json)")
    ap.add_argument("-j", "--workers", type=int, default=8, help="parallel Lean runs")
    args = ap.parse_args(argv)
    runs = [Path(p).resolve() for p in args.runs]
    if args.all:
        runs += sorted(p.parent for p in (ROOT / "runs").glob("*/qwen-v11/rep1/specs.json"))
    if not runs:
        ap.error("give run folders or --all")
    results = []
    for run in runs:
        res = score_run(run, args.workers)
        results.append(res)
        rows = res["rows"]
        print(f"[p11] {res['doc']}: {len(rows)} specs, scored {sum(not x['gate'] for x in rows)}, "
              f"mean payoff {statistics.mean([x['score'] for x in rows]) if rows else 0:.2f}", flush=True)
    text = report(results)
    if args.out:
        out = Path(args.out)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8")
        out.with_suffix(".json").write_text(json.dumps(results, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"[p11] -> {out}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
