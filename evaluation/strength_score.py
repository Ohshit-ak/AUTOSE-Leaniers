"""P11: a strength score for stored L0 specs (docs/design/p11_mechanism.md). No model; Lean only.

    python evaluation/strength_score.py runs/<doc>/qwen-v11/rep1 [...] [-o docs/analysis/strength_scores.md]
    python evaluation/strength_score.py --all [-o ...]       # every runs/*/qwen-v11/rep1

The harness (principal) pays the model (agent) for a contract:

    payoff = 0                      if the contract is unsatisfiable (does not compile, i.e. no
                                    checked `example` witness, or L0.5 found an output-free /
                                    unrealizable `post` conjunct),
                                    vacuous (it rejects none of the perturbed outputs below), or
                                    ungrounded (a constant in `pre`/`post` that the requirement
                                    text does not contain)
    payoff = killed / mutants       otherwise: the mutant-kill rate

Mutants are concrete outputs for the example's own input, generated by the harness:
  copy/constant  the outputs of the copy-and-constant implementations of `chain_checks`
                 (`_candidates`), evaluated on the example input (`x.f` → the input's value)
  perturbation   one field (or one field of a nested record) of the example output changed:
                 Nat ±1 and 0, Bool flipped, String "" and changed, List [] / doubled /
                 one extra element, Option none
A mutant is killed when Lean proves `¬ Spec.post <input> <mutant>` by `decide`. All mutants of
a spec are checked in one Lean run. Mutants equal to the example output are dropped.
"""
