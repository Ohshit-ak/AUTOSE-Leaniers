def p5() -> str:
    out = ["# P5: L0 v11 regressions on gamma j, ertms, dii", "",
           "Generated by `evaluation/analyze_p3_p4_p5_p6.py`. Old = L0 `qwen-v10.1/rep1` + chain-v5 "
           "(`qwen-chain-v5-on-v10.1`, 3 reps); new = L0 `qwen-v11/rep1` + chain-v5 (`qwen-chain-v5`, 3 reps), "
           "both strict. A spec counts as *lost* when it is end to end in more old reps than new reps "
           "(k/3 = reps end to end). Weak = `spec_check.trivial`.", ""]
    tot = Counter()
    rows_all = []
    for doc in P5_DOCS:
        d = RUNS / doc
        s_old, s_new = specs(d / "qwen-v10.1" / "rep1"), specs(d / "qwen-v11" / "rep1")
        r_old, r_new = review(d / "qwen-v10.1" / "rep1"), review(d / "qwen-v11" / "rep1")
        c_old, c_new = reps(d / "qwen-chain-v5-on-v10.1"), reps(d / "qwen-chain-v5")
        e2e = lambda rs, i: sum(bool(r.get(i, {}).get("full_check")) for r in rs)  # noqa: E731
        nt = lambda rs: [sum(1 for e in r.values() if e.get("full_check") and not weak(e)) for r in rs]  # noqa: E731
        tote = lambda rs: [sum(1 for e in r.values() if e.get("full_check")) for r in rs]  # noqa: E731
        ids = sorted(set(s_old) | set(s_new))
        lost, gained = [], []
        for i in ids:
            a, b = e2e(c_old, i), e2e(c_new, i)
            if a > b:
                lost.append((i, a, b))
            elif b > a:
                gained.append((i, a, b))
        out += [f"## {doc}", "",
                f"- end to end: old {spread(tote(c_old))}, new {spread(tote(c_new))}; "
                f"non-trivial: old {spread(nt(c_old))}, new {spread(nt(c_new))}",
                f"- accepted L0 specs into the chain: old {len(c_old[0]) if c_old else 0}, "
                f"new {len(c_new[0]) if c_new else 0}",
                f"- specs end to end in more reps before than after: **{len(lost)}**; the other way: {len(gained)}",
                "", "| id | old k/3 | new k/3 | L0.5 old → new | weak old → new | new failing stage (rep1) |",
                "|---|---|---|---|---|---|"]
        for i, a, b in lost:
            eo = next((r[i] for r in c_old if i in r), None)
            en = c_new[0].get(i) if c_new else None
            st_o = (r_old.get(i) or {}).get("status") or ((s_old.get(i) or {}).get("l05") or {}).get("status")
            st_n = (r_new.get(i) or {}).get("status") or ((s_new.get(i) or {}).get("l05") or {}).get("status")
            w_o = "weak" if eo and weak(eo) else ("strong" if eo else "?")
            w_n = ("weak" if weak(en) else "strong") if en else "–"
            if en is None and c_new:
                en = next((r[i] for r in c_new if i in r), None)
                w_n = ("weak" if weak(en) else "strong") if en else "–"
            if en is None:
                p_new = ((s_new.get(i) or {}).get("l05") or {}).get("problems") or \
                        ((s_new.get(i) or {}).get("l05") or {}).get("flags") or [(s_new.get(i) or {}).get("error") or "absent"]
                stage_note = " ".join(str(p_new[0]).split())[:90].replace("|", "\\|")
            else:
                stage_note = ""
            stage = fail_stage(en if (en is None or not en.get("full_check")) else
                               next((r[i] for r in c_new if i in r and not r[i].get("full_check")), en))
            tot["lost"] += 1
            tot[f"lost, old {w_o}"] += 1
            tot[f"lost, {w_o} → {w_n}"] += 1
            tot[f"lost at {stage.split(' ')[0] if stage.startswith(('L1', 'L2')) else stage}"] += 1
            tot[f"stage: {stage}"] += 1
            rows_all.append((doc, i, w_o, w_n, stage))
            out.append(f"| `{i}` | {a} | {b} | {st_o} → {st_n} | {w_o} → {w_n} | {stage}"
                       + (f": {stage_note}" if stage_note else "") + " |")
        tot["old e2e"] += statistics.mean(tote(c_old)) if c_old else 0
        tot["new e2e"] += statistics.mean(tote(c_new)) if c_new else 0
        tot["old nt"] += statistics.mean(nt(c_old)) if c_old else 0
        tot["new nt"] += statistics.mean(nt(c_new)) if c_new else 0
        out.append("")
    out += ["## Totals (3 SRS)", "",
            f"- end to end (sum of per-SRS means): old {tot['old e2e']:.1f}, new {tot['new e2e']:.1f}; "
            f"non-trivial: old {tot['old nt']:.1f}, new {tot['new nt']:.1f}",
            f"- lost specs: {tot['lost']}"]
    for k, v in sorted(tot.items()):
        if k.startswith(("lost,", "lost at", "stage:")):
            out.append(f"- {k}: {v}")
    return "\n".join(out) + "\n", tot


