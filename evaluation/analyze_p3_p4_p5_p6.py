_ERR_CLASSES = [
    ("invented Lean API (List./String./… name that does not exist)",
     r"environment does not contain `(list|string|char|nat|int|option|bool|array|function)\."),
    ("function expected", r"function expected"),
    ("fields missing in a record literal", r"fields missing"),
    ("unknown identifier / constant", r"unknown (identifier|constant)"),
    ("unknown field / not a field", r"(invalid field|is not a field|unknown field|has no field)"),
    ("type mismatch", r"type mismatch|application type mismatch"),
    ("failed to synthesize instance", r"failed to synthesize"),
    ("decide failed / proof", r"decide|unsolved goals|failed to prove|tactic .* failed|linarith|omega"),
    ("syntax / parse", r"unexpected token|expected|unterminated|parse"),
    ("already declared", r"already (been )?declared"),
    ("structure / deriving", r"deriving|structure"),
    ("timeout", r"timed out|heartbeats"),
    ("truncated / no code", r"truncat|empty|no lean"),
]


def first_error(err: str) -> str:
    from agents.repair import parse_errors
    errs = parse_errors(err or "")
    return (errs[0]["msg"] if errs else (err or "")).strip()


def err_class(msg: str) -> str:
    low = msg.lower()
    for name, rx in _ERR_CLASSES:
        if re.search(rx, low):
            return name
    return "other"


def problem_class(p: str) -> str:
    low = p.lower()
    for name, key in [("does not compile", "does not compile"),
                      ("accepts an output the requirement forbids (negative check)", "requirement forbids"),
                      ("output-mention: post conjunct only about the input (unrealizable)", "no implementation can make"),
                      ("vacuous post (accepts every changed output)", "changed output"),
                      ("vacuous / post ignores a field", "never mentions"),
                      ("housekeeping: `≥ 0` on a Nat", "always true for a `nat`"),
                      ("pre is True with a stated precondition", "`pre` is `true`"),
                      ("parser fact (runtime field / bound)", "bound"),
                      ("in-loop check failed (checked = false)", "in-loop"),
                      ("data test", "data test")]:
        if key in low:
            return name
    return "other: " + p[:60]


def p6():
    comp, l05, rows = Counter(), Counter(), []
    comp_ex = defaultdict(list)
    for d in sorted(RUNS.iterdir()):
        run = d / "qwen-v11" / "rep1"
        if not (run / "specs.json").exists():
            continue
        rv = review(run)
        for r in specs(run).values():
            st = (rv.get(r["id"]) or {}).get("status") or (r.get("l05") or {}).get("status")
            probs = (r.get("l05") or {}).get("problems") or []
            if not r.get("compiles"):
                msg = first_error(r.get("error") or "")
                c = err_class(msg)
                comp[c] += 1
                if len(comp_ex[c]) < 3:
                    comp_ex[c].append(f"{d.name} `{r['id']}`: {' '.join(msg.split())[:110]}")
            elif st == "fail":
                for p in dict.fromkeys(problem_class(p) for p in probs) or ["(no problem text)"]:
                    l05[p] += 1
            if st != "pass":
                rows.append({"doc": d.name, "id": r["id"], "kind": r["kind"],
                             "requirement": " ".join((r.get("requirement_text") or "").split()),
                             "status": st, "compiles": r.get("compiles"),
                             "first_problem": " ".join((first_error(r.get("error") or "") if not r.get("compiles") else
                                                        (probs or (r.get("l05") or {}).get("flags") or [""])[0])[:200].split()),
                             "human_verdict": "", "notes": ""})
    out = ["# P6: where L0 v11 loses entries (all 18 SRS, `qwen-v11/rep1`)", "",
           "Generated by `evaluation/analyze_p3_p4_p5_p6.py`. Per entry (the stored `summary.compiles` is "
           "stale, see `funnel.md`).", "",
           f"## Compile failures by first Lean error ({sum(comp.values())} entries)", "",
           "| first error | entries | examples |", "|---|---|---|"]
    for k, v in comp.most_common():
        out.append(f"| {k} | {v} | " + "<br>".join(x.replace("|", "\\|") for x in comp_ex[k]) + " |")
    out += ["", f"## L0.5 failures of compiling specs, by check ({sum(1 for r in rows if r['status'] == 'fail' and r['compiles'])} entries; "
            "an entry can fail more than one check)", "", "| check | entries |", "|---|---|"]
    for k, v in l05.most_common():
        out.append(f"| {k} | {v} |")
    rng = random.Random(0)
    sample = sorted(rng.sample(rows, min(20, len(rows))), key=lambda r: (r["doc"], r["id"]))
    with open(OUT / "p6_review.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(sample)
    out += ["", f"## Review sample", "", f"`p6_review.csv`: 20 of the {len(rows)} entries that are not L0.5 pass "
            "(random.Random(0)), columns `human_verdict` / `notes` to fill by hand "
            "(suggested verdicts: requirement not formalizable / model error / harness false alarm)."]
    return "\n".join(out) + "\n", comp, l05


