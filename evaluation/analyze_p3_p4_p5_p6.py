_L0_SPECS = {}


def _l0_specs(rep_dir: Path) -> dict:
    meta = json.loads((rep_dir / "chain_meta.json").read_text(encoding="utf-8"))
    l0 = ROOT / meta["l0_run"]
    if l0 not in _L0_SPECS:
        _L0_SPECS[l0] = specs(l0)
    return _L0_SPECS[l0]


def provenance_now(e: dict, l0: dict) -> list:
    """[(harness_only, {"harness": [...], "model": [...]})] per L2 component, with the provenance
    recomputed from the stored code by today's skeleton (H1 fix: a string literal containing
    " with " no longer makes every field the model's). Stored `fields` predate the fix."""
    import skeleton as SK
    import chain_checks as CC
    from validate import field_types
    locked = l0[e["id"]]["lean_predicate"] + "\n\n" + e["l1"]["code"]
    types = field_types(locked)
    contracts = {c.name: c for c in CC.parse_contracts(locked)}
    out = []
    for x in e.get("l2", []):
        c = contracts.get(x["contract"])
        f = x.get("fields") or {"harness": [], "model": []}
        if c is not None and x["success"] and x.get("fields") is not None:
            f = SK.provenance(x["code"], SK.build(c, types, f"{c.name}Impl"))
        out.append((bool(x.get("harness_only")), f))
    return out


def p4_p3():
    out = ["# P4 and P3: decomposition and who wrote the verified code (chain-v5, 18 SRS)", "",
           "Generated by `evaluation/analyze_p3_p4_p5_p6.py` from `qwen-chain-v5{,-fallback}/rep*/l1l2.json`. "
           "Sums over SRS of per-rep counts; mean (min–max) over the 3 reps (rep k of every SRS summed).", ""]
    summary = {}
    for run in ("qwen-chain-v5", "qwen-chain-v5-fallback"):
        per_doc = {}
        tot = defaultdict(lambda: [0, 0, 0])
        for d in sorted(RUNS.iterdir()):
            rs = reps(d / run)
            if not rs:
                continue
            row = defaultdict(list)
            rep_dirs = sorted((d / run).glob("rep*/l1l2.json"), key=lambda p: p.parent.name)
            for k, r in enumerate(rs[:3]):
                l0 = _l0_specs(rep_dirs[k].parent)
                es = list(r.values())
                l1 = lambda e: e.get("l1") or {}  # noqa: E731
                routed = [e for e in es if l1(e) and l1(e).get("mode") != "single"]
                chain_ok = [e for e in routed if l1(e).get("mode") == "chain" and l1(e).get("success")]
                chain_e2e = [e for e in chain_ok if e.get("full_check")]
                nd = [e for e in routed if l1(e).get("mode") == "single-not-decomposable"]
                fb = [e for e in routed if l1(e).get("mode") == "single-fallback"]
                full_nt = [e for e in es if e.get("full_check") and not weak(e)]
                prov = {e["id"]: provenance_now(e, l0) for e in full_nt}
                # harness-only: no component has a model-written field (H1-corrected), or the
                # harness skeleton alone implemented it (no model call)
                h_only = [e for e in full_nt if all(ho or not f["model"] for ho, f in prov[e["id"]])]
                rest = [e for e in full_nt if e not in h_only]
                fully = [e for e in rest if not any(f["harness"] for _, f in prov[e["id"]])]
                compl = [e for e in rest if e not in fully]
                vals = {"routed to a split": len(routed), "accepted chain": len(chain_ok),
                        "chain end to end": len(chain_e2e), "not decomposable": len(nd),
                        "single-fallback": len(fb), "failed split (L1 fail)": len(routed) - len(chain_ok) - len(nd) - len(fb),
                        "e2e non-trivial": len(full_nt), "harness-only": len(h_only),
                        "model-completed": len(compl), "model-fully": len(fully)}
                for key, v in vals.items():
                    row[key].append(v)
                    tot[key][k] += v
            per_doc[d.name] = row
        summary[run] = {k: v for k, v in tot.items()}
        out += [f"## {run}", "", "| | mean (min–max) |", "|---|---|"]
        for key, v in tot.items():
            out.append(f"| {key} | {spread(v)} |")
        rt, ch, ce = (statistics.mean(tot[x]) for x in ("routed to a split", "accepted chain", "chain end to end"))
        out += ["", f"**P4: {ch:.1f} of {rt:.1f} specs routed to a split were decomposed (accepted as a two-component "
                f"chain); {ce:.1f} of them verified end to end.**", "",
                "| SRS | routed | chain | chain e2e | not decomp. | fallback | e2e non-trivial | harness-only | "
                "model-completed | model-fully |", "|---" * 10 + "|"]
        for doc, row in per_doc.items():
            out.append(f"| {doc} | " + " | ".join(spread(row[k]) for k in
                       ("routed to a split", "accepted chain", "chain end to end", "not decomposable",
                        "single-fallback", "e2e non-trivial", "harness-only", "model-completed", "model-fully")) + " |")
        out.append("")
    out += ["P3 categories (verified end to end, non-trivial spec): **harness-only** = every component's code is the "
            "harness skeleton, no model call; **model-completed** = the model wrote code and the harness skeleton "
            "supplied ≥ 1 result field; **model-fully** = no result field came from the skeleton. "
            "Provenance is recomputed from the stored code with today's `skeleton.provenance` (H1 fix), "
            "not read from the stored `fields`; a component whose recomputed fields are all the harness's "
            "counts as harness-only. "
            "\n\n**H1 check.** The recompute changes no count here (strict model wrote code = 34.3 + 29.7 = 64.0, "
            "fallback 38.0 + 32.7 = 70.7). The two H1 records are: gamma j `CI-1` (all 6 reps), whose single "
            "component is stored with `harness_only: true`, so it was already harness-only in summarize_e2e's "
            "\"model wrote code\" (which tests `harness_only`, not `fields`); and peppol `1.1/S4` strict rep3, "
            "where only the second component's `included` moves from model to harness, while the first component "
            "already had a harness field, so the spec stays model-completed. The \"64.0 → 63.0 / 70.6 → 69.6\" "
            "correction in results.md and issues.tex subtracts CI-1 a second time; the H1-corrected values "
            "are 64.0 and 70.7 (70.6 with per-SRS rounding). "
            "harness-only + model-completed + model-fully = e2e non-trivial; model-completed + model-fully = "
            "summarize_e2e's \"non-trivial, model wrote code\"."]
    return "\n".join(out) + "\n", summary


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    t5, tot5 = p5()
    (OUT / "p5_l0_regression.md").write_text(t5, encoding="utf-8")
    t6, comp, l05 = p6()
    (OUT / "p6_l0_losses.md").write_text(t6, encoding="utf-8")
    t34, s34 = p4_p3()
    (OUT / "p4_p3_split.md").write_text(t34, encoding="utf-8")
    print(dict(tot5))
    print("compile:", comp.most_common())
    print("l05:", l05.most_common())
    for run, s in s34.items():
        print(run, {k: spread(v) for k, v in s.items()})
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
