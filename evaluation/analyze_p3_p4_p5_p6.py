"""Analyses P3, P4, P5 and P6 of docs/issues.tex, on stored runs only (no model, no Lean).

    python evaluation/analyze_p3_p4_p5_p6.py

Writes docs/analysis/p5_l0_regression.md, p6_l0_losses.md, p6_review.csv, p4_p3_split.md.

Definitions (same as evaluation/summarize_e2e.py):
  weak / trivial   `spec_check.trivial` is true (a copy-and-constants implementation satisfies Spec;
                   computed by chain_pipeline at chain time, so it exists for v10.1 specs too)
  end to end       `full_check` is true
  routed to a split   L1 mode is not "single" (the harness did not route it to one component):
                   accepted chains, failed splits (mode "chain", success false), "single-fallback"
                   and "single-not-decomposable"
  P3 split of verified non-trivial specs:
     harness-only     every L2 component is `harness_only`
     model-completed  some component used the model, and the harness wrote ≥1 result field
     model-fully      no result field of any component was written by the harness
"""
import csv
import json
import random
import re
import statistics
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RUNS = ROOT / "runs"
OUT = ROOT / "docs" / "analysis"
sys.path.insert(0, str(ROOT / "harness"))
from chain_failures import classify  # noqa: E402

P5_DOCS = ["0000 - gamma j", "2007-ertms", "1999 - dii"]


def reps(run: Path) -> list:
    out = []
    for p in sorted(run.glob("rep*/l1l2.json"), key=lambda p: p.parent.name):
        out.append({e["id"]: e for e in json.loads(p.read_text(encoding="utf-8"))})
    return out


def specs(run: Path) -> dict:
    p = run / "specs.json"
    return {r["id"]: r for r in json.loads(p.read_text(encoding="utf-8"))["results"]} if p.exists() else {}


def review(run: Path) -> dict:
    p = run / "review.json"
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else {}


def weak(e) -> bool:
    return (e.get("spec_check") or {}).get("trivial") is True


def spread(vals) -> str:
    if not vals:
        return "–"
    m = statistics.mean(vals)
    return f"{m:.1f} ({min(vals)}–{max(vals)})" if min(vals) != max(vals) else f"{m:.1f}"


def fail_stage(e) -> str:
    if e is None:
        return "not in chain (not accepted at L0)"
    if "crash" in e:
        return "crash"
    l1 = e.get("l1") or {}
    if not l1.get("success"):
        return f"L1 {l1.get('error_class') or classify(l1.get('error'), l1.get('stages'))}"
    bad = [x for x in e.get("l2", []) if not x["success"]]
    if bad:
        return "L2 " + "+".join(sorted({x.get("error_class") or classify(x.get("error"), x.get("stages"))
                                         for x in bad}))
    return "full_check false" if e.get("full_check") is False else "?"


