"""P6: the whole L0 → end-to-end funnel, with every L0 entry in the denominator.

    python evaluation/funnel.py [-o docs/analysis/funnel.md]

Reads only stored runs: runs/<doc>/qwen-v11/rep1/{specs,review}.json (L0 v11) and
runs/<doc>/qwen-chain-v5{,-fallback}/rep*/l1l2.json (chain-v5). Entries that never reach L1
count as not verified, so the end-to-end rate here is over parsed L0 entries, not over the
specs that pass L0.5. "Non-trivial" = `spec_check.trivial` is not true (as in summarize_e2e).
"""
import argparse
import json
import statistics
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RUNS = ROOT / "runs"


def _reps(run: Path) -> list:
    return [json.loads(p.read_text(encoding="utf-8")) for p in sorted(run.glob("rep*/l1l2.json"))]


def _e2e(reps: list) -> tuple:
    """(mean end to end, mean non-trivial end to end) over repetitions."""
    if not reps:
        return 0.0, 0.0
    full = [[e for e in d if e.get("full_check") is True] for d in reps]
    nt = [sum((e.get("spec_check") or {}).get("trivial") is not True for e in f) for f in full]
    return statistics.mean(len(f) for f in full), statistics.mean(nt)


def doc_row(doc: Path) -> dict:
    l0 = doc / "qwen-v11" / "rep1"
    specs = json.loads((l0 / "specs.json").read_text(encoding="utf-8"))["results"]
    review = json.loads((l0 / "review.json").read_text(encoding="utf-8"))
    status = Counter(review.get(r["id"], {}).get("status", "fail") for r in specs)
    s, s_nt = _e2e(_reps(doc / "qwen-chain-v5"))
    f, f_nt = _e2e(_reps(doc / "qwen-chain-v5-fallback"))
    return {"entries": len(specs), "compile": sum(bool(r.get("compiles")) for r in specs),
            "rejects bad example": sum(r.get("rejects_bad_example") is True for r in specs),
            "L0.5 pass": status["pass"], "L0.5 flag": status["flag"], "L0.5 fail": status["fail"],
            "e2e strict": s, "e2e fallback": f, "non-trivial strict": s_nt, "non-trivial fallback": f_nt}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("-o", "--out", default=str(ROOT / "docs" / "analysis" / "funnel.md"))
    args = ap.parse_args(argv)
    rows = {d.name: doc_row(d) for d in sorted(RUNS.iterdir()) if (d / "qwen-v11" / "rep1" / "specs.json").exists()}
    keys = list(next(iter(rows.values())))
    tot = {k: sum(r[k] for r in rows.values()) for k in keys}
    n, n05 = tot["entries"], tot["L0.5 pass"]
    pct = lambda x, d: f"{100 * x / d:.0f} %" if d else "–"  # noqa: E731
    out = ["# L0 → end-to-end funnel (L0 v11 + chain-v5, Qwen 2.5 7B, 18 SRS)", "",
           "Generated by `evaluation/funnel.py` from stored runs. End-to-end values are the mean over the 3 "
           "L1/L2 repetitions (all on the same L0 run). Every L0 entry is in the denominator.", "",
           "| stage | count | % of all L0 entries | % of specs that pass L0.5 |", "|---|---|---|---|"]
    for k in keys:
        v = tot[k]
        cell = f"{v:.1f}" if isinstance(v, float) else str(v)
        out.append(f"| {k} | {cell} | {pct(v, n)} | {pct(v, n05) if k.startswith(('e2e', 'non-trivial')) else ''} |")
    out += ["", "## Per SRS", "", "| SRS | " + " | ".join(keys) + " |", "|---" * (len(keys) + 1) + "|"]
    for d, r in rows.items():
        out.append(f"| {d} | " + " | ".join(f"{r[k]:.1f}" if isinstance(r[k], float) else str(r[k]) for k in keys) + " |")
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out[:4 + len(keys) + 2]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
